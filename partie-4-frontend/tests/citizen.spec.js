test('library distinguishes loading, network failure, retry, empty and incomplete metadata',async({page})=>{
  let release
  await page.route('**/api/documents',async route=>{
    await new Promise(resolve=>release=resolve)
    await route.abort('failed')
  })
  await page.goto('/#library')
  await expect(page.getByRole('status').last()).toContainText('Chargement')
  await expect(page.locator('.empty-state')).toHaveCount(0)
  release()
  await expect(page.getByRole('alert')).toContainText('Connexion')
  await page.route('**/api/documents',route=>route.fulfill({json:{documents:[],total:0,passages:0}}))
  await page.getByRole('button',{name:'Réessayer'}).click()
  await expect(page.locator('.empty-state')).toContainText('Aucun document disponible')
  await page.route('**/api/documents',route=>route.fulfill({json:{documents:[{document_id:'available-identifier-only',passages:3}],total:1,passages:3}}))
  await page.reload()
  await expect(page.locator('.document')).toContainText('available-identifier-only')
  await expect(page.locator('.document')).toContainText('Statut non renseigné')
  await expect(page.locator('.document a')).toHaveCount(0)
})


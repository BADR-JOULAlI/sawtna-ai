test('assistant HTTP error and retry, duplicate prevention, loading and keyboard entry',async({page})=>{
  let calls=0, release
  await page.route('**/api/ask',async route=>{
    calls++
    if(calls===1)return route.fulfill({status:503,json:{detail:'Internal information is not presented as localized UI'}})
    await new Promise(resolve=>release=resolve)
    await route.fulfill({json:answer})
  })
  await page.goto('/')
  await page.locator('#question').fill('Question citoyenne')
  await page.locator('#question').press('Shift+Enter')
  expect(await page.locator('#question').inputValue()).toContain('\n')
  await page.locator('#question').press('Enter')
  await expect(page.getByRole('alert')).toContainText('503')
  await page.getByRole('button',{name:'Réessayer'}).click()
  await expect(page.locator('.send-button')).toBeDisabled()
  await expect(page.getByRole('status')).toContainText('Recherche')
  await page.locator('#question').press('Enter')
  expect(calls).toBe(2)
  release()
  await expect(page.locator('.citation')).toHaveCount(1)
  await expect(page.getByRole('alert')).toHaveCount(0)
})


for(const language of ['fr','ar','darija']) for(const width of [360,390,768,1280]) {
  test(`${language} at ${width}px: all three journeys, overflow and browser errors`, async ({page}) => {
    const errors=[];page.on('pageerror',e=>errors.push(e.message))
    page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
    await page.setViewportSize({width,height:960})
    await page.goto('/')
    await page.getByRole('combobox').selectOption(language)
    await expect(page.locator('html')).toHaveAttribute('dir',language==='ar'?'rtl':'ltr')
    await expect(page.locator('html')).toHaveAttribute('lang',language==='darija'?'ary-Latn':language)
    await mkdir('work/screenshots',{recursive:true})
    const capture=async name=>{
      expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.evaluate(()=>window.scrollTo(0,0))
      await page.screenshot({path:`work/screenshots/${language}-${width}-${name}.png`,fullPage:true})
    }
    await capture('assistant')
    await page.locator('#question').fill(language==='ar'?'كيف يتم انتخاب أعضاء مجلس النواب؟':'Comment sont élus les représentants ?')
    const ask=page.waitForRequest(r=>new URL(r.url()).pathname==='/api/ask')
    await page.locator('.send-button').click()
    expect((await ask).postDataJSON().language).toBe(language)
    await expect(page.locator('.citation')).toHaveCount(1)
    await expect(page.locator('.response-section')).toBeFocused()
    await expect(page.locator('.citation a')).toHaveAttribute('href',/constitution.*#page=20$/)
    await capture('answer')
    await page.goto('/#library')
    await expect(page.locator('.document')).toHaveCount(2)
    await capture('library')
    await page.locator('input[type=search]').fill('nothing-matches')
    await expect(page.locator('.document')).toHaveCount(0)
    await expect(page.locator('.empty-state')).toBeVisible()
    await page.goto('/#quiz')
    await expect(page.locator('.quiz-form')).toBeVisible()
    await expect(page.locator('.corrections')).toHaveCount(0)
    await expect(page.locator('button[type=submit]')).toBeDisabled()
    await capture('quiz')
    await page.getByRole('radio').first().check()
    const submit=page.waitForRequest(r=>new URL(r.url()).pathname==='/api/quiz/submit')
    await page.locator('button[type=submit]').click()
    expect((await submit).postDataJSON()).toEqual({language,answers:{vote:0}})
    await expect(page.locator('.quiz-result')).toContainText('100')
    await expect(page.locator('.quiz-result')).toBeFocused()
    await capture('result')
    await page.locator('.primary-button').click()
    await expect(page.getByRole('radio').first()).not.toBeChecked()
    expect(errors).toEqual([])
  })
}


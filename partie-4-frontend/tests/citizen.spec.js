test('complete four-question quiz sends all indices and renders only the server score',async({page})=>{
  const fullQuiz={...quiz(),questions:[quiz().questions[0],
    {id:'chambers',question:'De combien de Chambres le Parlement est-il composé ?',options:['Une','Deux','Trois']},
    {id:'mandate',question:"Quelle durée est prévue pour l’élection des représentants dans le texte de 2011 ?",options:['Trois ans','Six ans','Cinq ans']},
    {id:'territories',question:'Quel élément est une collectivité territoriale ?',options:['Une commune','Un parti politique','Une commission parlementaire']},
  ]}
  await page.route('**/api/quiz?*',route=>route.fulfill({json:fullQuiz}))
  // Deliberately return a distinct authoritative score to detect client scoring.
  await page.route('**/api/quiz/submit',route=>route.fulfill({json:{correct:2,total:4,score:50,corrections:[]}}))
  await page.goto('/#quiz')
  for(const [name,index] of [['vote',0],['chambers',1],['mandate',2]])await page.locator(`input[name="${name}"]`).nth(index).check()
  await expect(page.locator('button[type=submit]')).toBeDisabled()
  await page.locator('input[name="territories"]').first().check()
  await expect(page.locator('progress')).toHaveAttribute('value','4')
  const request=page.waitForRequest('**/api/quiz/submit')
  await page.locator('button[type=submit]').click()
  expect((await request).postDataJSON()).toEqual({language:'fr',answers:{vote:0,chambers:1,mandate:2,territories:0}})
  await expect(page.locator('.quiz-result > strong')).toHaveText('50/100')
})

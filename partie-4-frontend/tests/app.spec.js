import { test, expect } from '@playwright/test'
test('assistant returns actual source passages and no browser errors',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{level:1})).toContainText('Comprendre le vote.')
  await page.screenshot({path:'../commun/docs/verification/accueil-desktop.png',fullPage:true})
  await page.getByRole('textbox',{name:'Quelle est votre question ?'}).fill('Comment sont élus les membres de la Chambre des représentants ?')
  await page.getByRole('button',{name:'Envoyer la question',exact:true}).click()
  await expect(page.locator('.citation').first()).toBeVisible()
  await expect(page.locator('.citation-list')).toContainText('cinq ans')
  await expect(page.locator('.citation a').first()).toHaveAttribute('href',/https:\/\/maroc.ma/)
  expect(errors).toEqual([])
  await page.screenshot({path:'../commun/docs/verification/assistant-desktop.png',fullPage:true})
})
test('library search and official document link',async({page})=>{
  await page.goto('/#library')
  await expect(page.locator('.document')).toHaveCount(1)
  await page.getByRole('textbox',{name:'Rechercher un document'}).fill('does-not-exist')
  await expect(page.locator('.document')).toHaveCount(0)
  await page.getByRole('textbox',{name:'Rechercher un document'}).fill('Constitution')
  await expect(page.locator('.document-link')).toHaveAttribute('href',/https:\/\/maroc.ma/)
})
test('quiz is submitted to the backend and displays score and citations',async({page})=>{
  await page.goto('/#quiz')
  for(const [name,index] of [['vote',0],['chambers',1],['mandate',2],['territories',0]]){
    await page.locator('input[name="'+name+'"]').nth(index).check()
  }
  await page.getByRole('button',{name:'Voir mes résultats'}).click()
  await expect(page.locator('.quiz-result')).toContainText('100')
  await expect(page.locator('.corrections a')).toHaveCount(4)
})
test('Arabic layout and Darija retrieval',async({page})=>{
  await page.goto('/')
  await page.getByRole('combobox').selectOption('ar')
  await expect(page.locator('html')).toHaveAttribute('dir','rtl')
  await page.getByRole('textbox').fill('كيف يتم انتخاب أعضاء مجلس النواب؟')
  await page.getByRole('button',{name:'إرسال السؤال'}).click()
  await expect(page.locator('.citation').first()).toBeVisible()
  await page.getByRole('combobox').selectOption('darija')
  await expect(page.locator('html')).toHaveAttribute('dir','ltr')
  await page.getByRole('textbox').fill('Kifach kaytntakhbo nowab?')
  await page.getByRole('button',{name:'Sift sou2al'}).click()
  await expect(page.locator('.question-sent')).toContainText('nowab')
  await expect(page.locator('.citation').first()).toBeVisible()
})
test('admin rejects bad credentials then displays live analytics',async({page})=>{
  await page.goto('/#dashboard')
  await page.getByLabel('Clé administrateur').fill('wrong')
  await page.getByRole('button',{name:'Ouvrir le tableau de bord'}).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByLabel('Clé administrateur').fill(process.env.SAWTNA_ADMIN_KEY||'local-sawtna-admin-only')
  await page.getByRole('button',{name:'Ouvrir le tableau de bord'}).click()
  await expect(page.locator('.kpi')).toHaveCount(4)
  await expect(page.getByRole('img',{name:'Nombre de questions par jour'})).toBeVisible()
  await page.screenshot({path:'../commun/docs/verification/dashboard-desktop.png',fullPage:true})
})
test('mobile navigation fits the screen',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.getByRole('button',{name:'Menu',exact:true}).click()
  await page.getByRole('link',{name:'Bibliothèque',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Les textes, à la source.'})).toBeVisible()
  await page.goto('/')
  await page.screenshot({path:'../commun/docs/verification/assistant-mobile.png',fullPage:true})
})
test('failed API request produces an actionable error',async({page})=>{
  await page.route('**/api/ask',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Service NLP indisponible'})}))
  await page.goto('/')
  await page.getByRole('textbox').fill('Comment sont élus les représentants ?')
  await page.getByRole('button',{name:'Envoyer la question',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('Service NLP indisponible')
})
